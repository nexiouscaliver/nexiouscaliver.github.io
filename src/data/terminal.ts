// Everything the /terminal page knows, as data. terminal.astro renders the
// script-off transcript from this module and serializes a lean copy to the
// live terminal (representative lines, examples, and flags stay static-only
// for visible commands), so adding a command is a content edit: it lands in
// help, in tab completion, and in the static transcript in the same change.
//
// Link lines carry a token in `href` that the page resolves against the site
// settings before anything ships: site:resume, site:email, site:github,
// site:linkedin, site:projects. Everything else passes through as-is.

export type TermClass = 'dim' | 'bright' | 'amber' | 'err' | 'ok';

/** A printed line: plain text, or a link. */
export type TermLine =
  | { t: string; c?: TermClass }
  | { a: string; href: string; c?: TermClass };

/** A file in the flat read-only home. bin marks refuse-to-cat entries. */
export interface TermFile {
  path: string;
  lines?: TermLine[];
  bin?: string;
  payload?: string;
  size?: number;
}

export type TermAction =
  | 'clear' | 'help' | 'man' | 'ls' | 'cat' | 'cd' | 'pwd' | 'head' | 'wc'
  | 'file' | 'echo' | 'whoami' | 'uname' | 'date' | 'history' | 'base64'
  | 'rot13' | 'xxd' | 'sha256' | 'ping' | 'curl' | 'nmap' | 'exit'
  | 'sudo' | 'su' | 'ssh' | 'gpg' | 'sqlmap' | 'hydra' | 'nikto' | 'rm' | 'touch';

export interface TermCommand {
  /** What the user types. Lowercase, one word. */
  name: string;
  /** Argument hint shown in help and man SYNOPSIS, if any. */
  args?: string;
  /** One line of help text. */
  summary: string;
  /** Representative output for the script-off transcript. */
  lines?: TermLine[];
  /** Behavioral commands instead of printed lines. */
  action?: TermAction;
  /** Fixed operand for alias-style commands (about -> cat about.md). */
  file?: string;
  /** What the static transcript prompt shows after the command name. */
  example?: string;
  /** Flag documentation. TS-side only; the serializer strips it. */
  flags?: string[];
  /** Easter eggs: absent from help, transcript, completion, and suggestions. */
  hidden?: boolean;
}

